package org.example;

public class CalculatorService {

    //Addition
    public int add(int a, int b){
        return a+b;
    }

    //substraction
    public int sub(int a, int b){
        return a-b;
    }

    //multiplication
    public int mul(int a,int b){
        return a*b;
    }

    //Division
    public int div(int a,int b){
        return a/b;
    }
}
